// Generates the string module the provider packages embed into a bundle as
// `awaitstep/runtime.ts`. The source is read from this package so the emitted
// module and the authoring surface cannot drift.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const source = await readFile(join(root, 'src', 'runtime.ts'), 'utf8')
const output = `// Generated by scripts/emit-runtime-source.mjs — do not edit.
export const RUNTIME_MODULE_SOURCE = ${JSON.stringify(source)}
`
await writeFile(join(root, 'src', 'runtime-source.ts'), output, 'utf8')
