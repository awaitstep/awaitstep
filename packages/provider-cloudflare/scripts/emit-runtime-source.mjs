// Generates the string module codegen embeds as `awaitstep/cloudflare.ts`.
// The source is this package's own Cloudflare primitive module, so the
// emitted module and the checked-in source cannot drift.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const source = await readFile(join(root, 'src', 'runtime', 'cloudflare.ts'), 'utf8')
const output = `// Generated by scripts/emit-runtime-source.mjs — do not edit.
export const CLOUDFLARE_PRIMITIVES_SOURCE = ${JSON.stringify(source)}
`
await writeFile(join(root, 'src', 'runtime', 'cloudflare-source.ts'), output, 'utf8')
