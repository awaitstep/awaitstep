// Generates the string module codegen embeds as `awaitstep/cloudflare.ts`.
// The source is this package's own Cloudflare primitive module, so the
// emitted module and the checked-in source cannot drift.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const source = await readFile(join(root, 'src', 'runtime', 'cloudflare.ts'), 'utf8')
const output = `// Generated by scripts/emit-runtime-source.mjs — do not edit.
export const CLOUDFLARE_PRIMITIVES_SOURCE = ${JSON.stringify(source)}
`
await writeFile(join(root, 'src', 'runtime', 'cloudflare-source.ts'), output, 'utf8')

// The schedule rules a generated Worker runs for an entry in a timezone: the
// same source the app uses to show next times, so the two cannot disagree.
const scheduleDir = join(root, '..', 'ir', 'src', 'schedule')
const scheduleParts = await Promise.all(
  ['cron.ts', 'zone.ts', 'due.ts'].map((file) => readFile(join(scheduleDir, file), 'utf8')),
)
const scheduleSource = scheduleParts
  .map((part) => part.replace(/^import [^\n]*\n/gm, ''))
  .join('\n')
const scheduleOutput = `// Generated by scripts/emit-runtime-source.mjs — do not edit.
export const SCHEDULE_RUNTIME_SOURCE = ${JSON.stringify(scheduleSource)}
`
await writeFile(join(root, 'src', 'runtime', 'schedule-source.ts'), scheduleOutput, 'utf8')
